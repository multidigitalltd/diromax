/**
 * The client's overrides. Read once per request.
 *
 * @return array<string,mixed>
 */
function dx_content_overrides() {
	static $overrides = null;

	if ( null === $overrides ) {
		$stored    = get_option( DX_CONTENT_OPTION, array() );
		$overrides = is_array( $stored ) ? $stored : array();
	}

	return $overrides;
}

/**
 * Resolve one content value: the client's version if there is one, else the default.
 *
 * @param string $key Key in "group.field" form.
 * @return mixed String, array of rows, or '' when the key is unknown.
 */
function dx_content( $key ) {
	$parts = explode( '.', $key, 2 );

	if ( 2 !== count( $parts ) ) {
		return '';
	}

	list( $group, $field ) = $parts;

	$overrides = dx_content_overrides();
	$value     = $overrides[ $group ][ $field ] ?? null;

	if ( null === $value ) {
		$defaults = dx_content_defaults( $group );
		$value    = $defaults[ $field ] ?? '';
	}

	/**
	 * Filter a resolved content value.
	 *
	 * @param mixed  $value Resolved value.
	 * @param string $key   Content key.
	 */
	return apply_filters( 'dx_content', $value, $key );
}

/**
 * Echo a content value as escaped text.
 *
 * @param string $key Content key.
 */
function dx_the_text( $key ) {
	echo esc_html( (string) dx_content( $key ) );
}

/**
 * Echo a content value, turning the line breaks the editor typed into <br>.
 *
 * @param string $key Content key.
 */
function dx_the_lines( $key ) {
	$value = esc_html( (string) dx_content( $key ) );

	echo str_replace( array( "\r\n", "\n" ), '<br>', $value ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped above; only <br> is reintroduced.
}

/**
 * Repeater rows for a key, always an array.
 *
 * @param string $key Content key.
 * @return array
 */
function dx_rows( $key ) {
	$value = dx_content( $key );

	return is_array( $value ) ? $value : array();
}

